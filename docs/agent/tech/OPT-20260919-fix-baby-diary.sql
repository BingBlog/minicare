-- ── §0 前置校验 ────────────────────────────────────────────────────────────
-- 确认目标行存在、且 09-18 当天没有其它日记（避免撞 UNIQUE(baby_id, diary_date)）
SELECT id, diary_date, LEFT(content, 40) AS head
FROM baby_diary
ORDER BY diary_date DESC;
-- 期望：仅 3 行（2026-09-19 / 2026-09-07 / 2026-08-25），不存在 2026-09-18


-- ── §1 日期错位 ────────────────────────────────────────────────────────────
-- 现象：正文首行写「2026.09.18｜旺仔8个月21天」，diary_date 却落成 2026-09-19
-- 成因：小程序 openDraft() 硬编码 nowDate()，且 tool_call 事件丢弃了 generate_diary 的 input.date
-- 修复：改为 2026-09-18（与正文自洽）
UPDATE baby_diary
SET diary_date = '2026-09-18',
    updated_at = NOW()
WHERE id = '945d5ba2-f417-493b-bbbe-345522886f9f'
  AND diary_date = '2026-09-19';


