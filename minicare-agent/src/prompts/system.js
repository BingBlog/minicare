/**
 * Few-shot 示例：给定真实数据时，期望的回答格式与结构（2026-08-24 注入，
 * 2026-09-04 按"先按天/先按周、后汇总"重写示例一/二）。
 * 仅作格式与结构示范，数据一律以实际查询结果为准。
 */
